-- This table stores event registration personal data. Keep access private.
create table if not exists public.registrations (
  id bigint generated by default as identity primary key,
  team_name text check (team_name is null or char_length(team_name) between 2 and 60),
  full_name text not null check (char_length(full_name) between 3 and 100),
  student_id text not null constraint registrations_student_id_key unique check (student_id ~ '^[A-Za-z0-9][A-Za-z0-9/-]{0,31}$'),
  phone text not null check (phone ~ '^\+91[6-9]\d{9}$'),
  email text not null constraint registrations_email_key unique check (char_length(email) <= 120),
  course text not null,
  academic_year smallint not null check (academic_year between 1 and 4),
  branch text,
  semester smallint check (semester between 1 and 8),
  team_size smallint not null default 1 check (team_size in (1, 2)),
  member2_name text,
  member2_phone text check (member2_phone is null or member2_phone ~ '^\+91[6-9]\d{9}$'),
  member2_email text,
  member2_course text,
  member2_academic_year smallint check (member2_academic_year is null or member2_academic_year between 1 and 4),
  member2_branch text,
  registration_code text not null constraint registrations_registration_code_key unique,
  created_at timestamptz not null default now()
);

create index if not exists registrations_created_at_idx on public.registrations (created_at desc);

comment on column public.registrations.student_id is 'Enrollment number, up to 32 letters or numbers';

