-- Run this once in Supabase Dashboard → SQL Editor.
-- This table stores event registration personal data. Keep access private.
create table if not exists public.registrations (
  id bigint generated by default as identity primary key,
  full_name text not null check (char_length(full_name) between 3 and 100),
  student_id text not null constraint registrations_student_id_key unique check (student_id ~ '^\d{11}$'),
  phone text not null check (phone ~ '^\+91[6-9]\d{9}$'),
  email text not null constraint registrations_email_key unique check (char_length(email) <= 120),
  course text not null,
  academic_year smallint not null check (academic_year between 1 and 4),
  semester smallint not null check (semester between 1 and 8),
  registration_code text not null constraint registrations_registration_code_key unique,
  created_at timestamptz not null default now()
);

create index if not exists registrations_created_at_idx on public.registrations (created_at desc);

comment on column public.registrations.student_id is '11-digit enrollment number';

alter table public.registrations enable row level security;
revoke all on table public.registrations from public, anon, authenticated;
grant all on table public.registrations to service_role;
